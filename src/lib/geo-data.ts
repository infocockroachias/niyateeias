export const GEO_ITEMS: GeoItem[] = [
  ...PLACES,
  ...RIVERS,
  ...RANGES,
  ...STRAITS,
  ...PORTS,
  ...PROJECTS,
  ...HERITAGE,
  ...ECOLOGY,
];

export function getCategory(key: GeoCategoryKey): GeoCategory {
  return GEO_CATEGORIES.find((c) => c.key === key) ?? GEO_CATEGORIES[0];
}

export function pointItems(): GeoItem[] {
  return GEO_ITEMS.filter((i) => i.kind === "point");
}

export function lineItems(): GeoItem[] {
  return GEO_ITEMS.filter((i) => i.kind === "line");
}

/** Great-circle distance in km between two [lat, lng] pairs */
export function haversineKm(a: [number, number], b: [number, number]): number {
  const R = 6371;
  const toRad = (d: number) => (d * Math.PI) / 180;
  const dLat = toRad(b[0] - a[0]);
  const dLng = toRad(b[1] - a[1]);
  const s =
    Math.sin(dLat / 2) ** 2 +
    Math.cos(toRad(a[0])) * Math.cos(toRad(b[0])) * Math.sin(dLng / 2) ** 2;
  return 2 * R * Math.asin(Math.min(1, Math.sqrt(s)));
}

/** Search helper — name + region + facts + tags */
export function searchGeoItems(query: string, items: GeoItem[] = GEO_ITEMS): GeoItem[] {
  const q = query.trim().toLowerCase();
  if (!q) return items;
  return items.filter(
    (i) =>
      i.name.toLowerCase().includes(q) ||
      (i.region ?? "").toLowerCase().includes(q) ||
      i.facts.some((f) => f.toLowerCase().includes(q)) ||
      i.tags.some((t) => t.toLowerCase().includes(q))
  );
}
